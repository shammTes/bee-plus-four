String highLabel(String lang, String key, [Map<String, Object>? vars]) {
  var s = kHighLabels[lang]?[key] ?? kHighLabels['en']?[key] ?? kLabels[lang]?[key] ?? kLabels['en']?[key] ?? key;
  if (vars != null) {
    s = s.replaceAllMapped(RegExp(r'\{(\w+)\}'), (m) => vars[m[1]]?.toString() ?? m[0]!);
  }
  return s;
}

String _subjSlug(String name) {
  final s = name.toLowerCase().replaceAll('&', 'and').replaceAll(RegExp(r'[^a-z0-9]+'), '_');
  return s.replaceAll(RegExp(r'_+'), '_').replaceAll(RegExp(r'^_|_\$'), '');
}

String subjectTr(String lang, String name) {
  final slug = _subjSlug(name);
  return kHighLabels[lang]?['subj_\$slug'] ?? kHighLabels['en']?['subj_\$slug'] ?? name;
}

String greetingFor(String lang) {
  final h = DateTime.now().hour;
  if (h < 12) return highLabel(lang, 'goodMorning');
  if (h < 17) return highLabel(lang, 'goodAfternoon');
  return highLabel(lang, 'goodEvening');
}
